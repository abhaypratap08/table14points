-- Points Tracker schema for a new Supabase project.
-- Run this once in Supabase Dashboard -> SQL Editor.

create table if not exists public.members (
  id bigint generated by default as identity primary key,
  name text not null,
  points integer not null default 0 check (points >= 0)
);

create table if not exists public.point_log (
  id bigint generated by default as identity primary key,
  member_id bigint not null references public.members(id) on delete cascade,
  amount integer not null check (amount <> 0),
  created_at timestamptz not null default now()
);

create or replace function public.add_points(p_member_id bigint)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  new_points integer;
begin
  update public.members
  set points = points + 5
  where id = p_member_id
  returning points into new_points;

  if not found then
    raise exception 'Member not found';
  end if;

  insert into public.point_log (member_id, amount)
  values (p_member_id, 5);

  return new_points;
end;
$$;

create or replace function public.subtract_points(p_member_id bigint)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  new_points integer;
begin
  update public.members
  set points = points - 5
  where id = p_member_id and points >= 5
  returning points into new_points;

  if not found then
    raise exception 'Member not found or points are already zero';
  end if;

  insert into public.point_log (member_id, amount)
  values (p_member_id, -5);

  return new_points;
end;
$$;

revoke all on function public.add_points(bigint) from public;
revoke all on function public.subtract_points(bigint) from public;
grant execute on function public.add_points(bigint) to anon, authenticated;
grant execute on function public.subtract_points(bigint) to anon, authenticated;

alter table public.members enable row level security;
alter table public.point_log enable row level security;

drop policy if exists "Anyone can read members" on public.members;
create policy "Anyone can read members"
  on public.members for select
  to anon, authenticated
  using (true);

drop policy if exists "Anyone can read point log" on public.point_log;
create policy "Anyone can read point log"
  on public.point_log for select
  to anon, authenticated
  using (true);

